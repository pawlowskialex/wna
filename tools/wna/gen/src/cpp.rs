//! Header-only C++20 bindings over the C headers: one namespace per
//! interface (`acme::core::storage`), `std::expected` results, variants as
//! `std::variant` of case structs, move-only RAII handles, and abstract
//! `Exports` classes whose table slots are `noexcept` and never unwind.

use crate::Files;
use crate::c::{c_type, field};
use anyhow::Result;
use std::collections::{HashMap, HashSet};
use std::fmt::Write;
use wna_abi::wit_parser::*;
use wna_abi::*;

pub const RUNTIME: &str = include_str!("../../cpp/wna.hpp");

#[derive(Copy, Clone, PartialEq, Eq)]
enum Dir {
    Import,
    Export,
}

/// Writes the C headers, `wna.hpp`, and `<world>.hpp`.
pub fn generate(wit: &Wit, world: WorldId, out: &mut Files) -> Result<()> {
    let (imports, exports) = wit.world_interfaces(world)?;
    for &i in imports.iter().chain(&exports) {
        wit.check_v0(i)?;
    }
    crate::c::generate(wit, &imports.iter().chain(&exports).copied().collect::<Vec<_>>(), out);
    out.insert("wna.hpp".into(), RUNTIME.into());

    let mut all = Vec::new();
    fn add(wit: &Wit, i: InterfaceId, all: &mut Vec<InterfaceId>) {
        if all.contains(&i) {
            return;
        }
        for u in used_interfaces(wit, i) {
            add(wit, u, all);
        }
        all.push(i);
    }
    for &i in imports.iter().chain(&exports) {
        add(wit, i, &mut all);
    }
    let w = &wit.resolve.worlds[world];
    let mut g = Gen {
        wit,
        dirs: all.iter().map(|&i| (i, if exports.contains(&i) { Dir::Export } else { Dir::Import })).collect(),
        decls: String::new(),
        helpers: String::new(),
        done: HashSet::new(),
        detail: format!("wna_detail_{}", ident(&w.name)),
        imports: imports.clone(),
        exports: exports.clone(),
    };
    let mut types = String::new();
    let mut defs = String::new();
    for &i in &all {
        types.push_str(&g.types(i));
    }
    for &i in &all {
        defs.push_str(&g.functions(i));
    }
    let mut s = String::new();
    writeln!(s, "// Generated by wna-gen from world {}. Do not edit.\n#pragma once\n\n#include \"wna.hpp\"", w.name).unwrap();
    for &i in &all {
        writeln!(s, "#include \"{}\"", crate::c::header_name(wit, i)).unwrap();
    }
    s.push('\n');
    s.push_str(&types);
    writeln!(s, "namespace {} {{\n{}\n{}}}  // namespace {}\n", g.detail, g.decls, g.helpers, g.detail).unwrap();
    s.push_str(&defs);
    s.push_str(&g.world(world));
    out.insert(format!("{}.hpp", ident(&w.name)), s);
    Ok(())
}

struct Gen<'a> {
    wit: &'a Wit,
    dirs: HashMap<InterfaceId, Dir>,
    decls: String,
    helpers: String,
    done: HashSet<String>,
    detail: String,
    imports: Vec<InterfaceId>,
    exports: Vec<InterfaceId>,
}

const CPP_KEYWORDS: &[&str] = &[
    "alignas", "alignof", "and", "asm", "auto", "bool", "break", "case", "catch", "char", "class", "const", "constexpr",
    "continue", "default", "delete", "do", "double", "else", "enum", "explicit", "export", "extern", "false", "float", "for",
    "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "nullptr",
    "operator", "or", "private", "protected", "public", "register", "return", "short", "signed", "sizeof", "static",
    "struct", "switch", "template", "this", "throw", "true", "try", "typedef", "typename", "union", "unsigned", "using",
    "virtual", "void", "volatile", "while", "xor", "concept", "requires", "module", "import", "self", "small", "wide",
];

fn ident(s: &str) -> String {
    let n = snake(s);
    if CPP_KEYWORDS.contains(&n.as_str()) { format!("{n}_") } else { n }
}

fn tname(s: &str) -> String {
    upper_camel(s)
}

fn docs(d: &Docs, indent: &str) -> String {
    let mut s = String::new();
    if let Some(c) = &d.contents {
        for l in c.lines() {
            writeln!(s, "{indent}/// {l}").unwrap();
        }
    }
    s
}

impl<'a> Gen<'a> {
    fn ns(&self, iface: InterfaceId) -> String {
        let i = &self.wit.resolve.interfaces[iface];
        let p = &self.wit.resolve.packages[i.package.unwrap()].name;
        format!("{}::{}::{}", ident(&p.namespace), ident(&p.name), ident(i.name.as_ref().unwrap()))
    }

    fn res_dir(&self, r: TypeId) -> Dir {
        self.dirs[&owner_iface(self.wit, self.wit.dealias_id(r)).unwrap()]
    }

    fn res_path(&self, r: TypeId) -> String {
        let r = self.wit.dealias_id(r);
        format!("::{}::{}", self.ns(owner_iface(self.wit, r).unwrap()), tname(self.wit.resolve.types[r].name.as_ref().unwrap()))
    }

    fn res_index(&self, r: TypeId) -> usize {
        let r = self.wit.dealias_id(r);
        let i = owner_iface(self.wit, r).unwrap();
        self.wit.resolve.interfaces[i].types.values().filter(|t| matches!(self.wit.resolve.types[**t].kind, TypeDefKind::Resource)).position(|t| *t == r).unwrap()
    }

    /// Owned C++ type.
    fn ty(&self, ty: Type) -> String {
        match ty {
            Type::Bool => "bool".into(),
            Type::U8 => "uint8_t".into(),
            Type::U16 => "uint16_t".into(),
            Type::U32 => "uint32_t".into(),
            Type::U64 => "uint64_t".into(),
            Type::S8 => "int8_t".into(),
            Type::S16 => "int16_t".into(),
            Type::S32 => "int32_t".into(),
            Type::S64 => "int64_t".into(),
            Type::F32 => "float".into(),
            Type::F64 => "double".into(),
            Type::Char => "char32_t".into(),
            Type::String => "std::string".into(),
            Type::ErrorContext => unreachable!(),
            Type::Id(id) => {
                let t = &self.wit.resolve.types[id];
                match &t.kind {
                    TypeDefKind::Type(inner) => self.ty(*inner),
                    TypeDefKind::Handle(Handle::Own(r)) => match self.res_dir(*r) {
                        Dir::Import => self.res_path(*r),
                        Dir::Export => format!("std::shared_ptr<{}Resource>", self.res_path(*r)),
                    },
                    TypeDefKind::Handle(Handle::Borrow(r)) => match self.res_dir(*r) {
                        Dir::Import => format!("const {}&", self.res_path(*r)),
                        Dir::Export => format!("{}Resource&", self.res_path(*r)),
                    },
                    _ if t.name.is_some() => format!("::{}::{}", self.ns(owner_iface(self.wit, id).unwrap()), tname(t.name.as_ref().unwrap())),
                    TypeDefKind::List(e) => format!("std::vector<{}>", self.ty(*e)),
                    TypeDefKind::Option(e) => format!("std::optional<{}>", self.ty(*e)),
                    TypeDefKind::Result(r) => format!("::wna::expected<{}, {}>", r.ok.map(|t| self.ty(t)).unwrap_or_else(|| "void".into()), r.err.map(|t| self.ty(t)).unwrap_or_else(|| "::wna::unit".into())),
                    TypeDefKind::Tuple(tu) => format!("std::tuple<{}>", tu.types.iter().map(|t| self.ty(*t)).collect::<Vec<_>>().join(", ")),
                    k => panic!("unsupported {k:?}"),
                }
            }
        }
    }

    /// Import parameter type.
    fn param(&self, ty: Type) -> String {
        match ty {
            Type::String => "std::string_view".into(),
            Type::Id(id) => match &self.wit.resolve.types[id].kind {
                TypeDefKind::Type(t) => self.param(*t),
                TypeDefKind::List(e) if self.wit.resolve.types[id].name.is_none() => format!("std::span<const {}>", self.ty(*e)),
                TypeDefKind::Handle(_) | TypeDefKind::Enum(_) | TypeDefKind::Flags(_) => self.ty(ty),
                _ => format!("const {}&", self.ty(ty)),
            },
            _ => self.ty(ty),
        }
    }

    fn lower(&mut self, i: InterfaceId, ty: Type, v: &str) -> String {
        match ty {
            Type::Char => format!("static_cast<uint32_t>({v})"),
            Type::String => format!("cx.string({v})"),
            Type::Id(id) => match &self.wit.resolve.types[id].kind {
                TypeDefKind::Type(t) => self.lower(i, *t, v),
                TypeDefKind::Enum(_) | TypeDefKind::Flags(_) => format!("static_cast<{}>({v})", c_type(self.wit, i, ty)),
                TypeDefKind::Handle(h) => {
                    let r = self.wit.resource_of(h);
                    match (self.res_dir(r), h) {
                        (Dir::Import, Handle::Own(_)) => format!("const_cast<{}&>({v}).release()", self.res_path(r)),
                        (Dir::Import, Handle::Borrow(_)) => format!("{v}.handle()"),
                        (Dir::Export, Handle::Own(_)) => format!("{}::box_of(cx)->res{}.insert({v})", self.res_owner_ns(r), self.res_index(r)),
                        (Dir::Export, Handle::Borrow(_)) => "throw ::wna::trap(WNA_TRAP_INVALID, \"borrowing a C++-exported resource across an import is not supported\")".into(),
                    }
                }
                _ => {
                    let f = self.helper(i, ty);
                    format!("{}::lower_{f}({v}, cx)", self.detail)
                }
            },
            _ => v.to_string(),
        }
    }

    fn lift(&mut self, i: InterfaceId, ty: Type, c: &str) -> String {
        match ty {
            Type::Char => format!("::wna::lift_char({c})"),
            Type::String => format!("cx.string({c})"),
            Type::Bool => format!("static_cast<bool>({c})"),
            Type::Id(id) => match &self.wit.resolve.types[id].kind {
                TypeDefKind::Type(t) => self.lift(i, *t, c),
                TypeDefKind::Flags(_) => format!("static_cast<{}>({c})", self.ty(ty)),
                TypeDefKind::Handle(h) => {
                    let r = self.wit.resource_of(h);
                    match (self.res_dir(r), h) {
                        (Dir::Import, Handle::Own(_)) => format!("{}(::wna::adopt, {c})", self.res_path(r)),
                        (Dir::Import, Handle::Borrow(_)) => format!("{}::borrow({c})", self.res_path(r)),
                        (Dir::Export, Handle::Own(_)) => format!("{}::box_of(cx)->res{}.remove({c})", self.res_owner_ns(r), self.res_index(r)),
                        (Dir::Export, Handle::Borrow(_)) => format!("*{}::box_of(cx)->res{}.get({c})", self.res_owner_ns(r), self.res_index(r)),
                    }
                }
                _ => {
                    let f = self.helper(i, ty);
                    format!("{}::lift_{f}({c}, cx)", self.detail)
                }
            },
            _ => c.to_string(),
        }
    }

    fn res_owner_ns(&self, r: TypeId) -> String {
        format!("::{}", self.ns(owner_iface(self.wit, self.wit.dealias_id(r)).unwrap()))
    }

    /// Emits `lower_<ctype>`/`lift_<ctype>` once; returns `<ctype>`.
    fn helper(&mut self, i: InterfaceId, ty: Type) -> String {
        let ct = c_type(self.wit, i, ty);
        if !self.done.insert(ct.clone()) {
            return ct;
        }
        let Type::Id(id) = ty else { unreachable!() };
        let i = owner_iface(self.wit, id).filter(|_| self.wit.resolve.types[id].name.is_some()).unwrap_or(i);
        let t = self.ty(ty);
        let (mut lo, mut li) = (String::new(), String::new());
        match self.wit.resolve.types[id].kind.clone() {
            TypeDefKind::Record(r) => {
                writeln!(lo, "  {ct} c{{}};").unwrap();
                for f in &r.fields {
                    let e = self.lower(i, f.ty, &format!("v.{}", ident(&f.name)));
                    writeln!(lo, "  c.{} = {e};", field(&f.name)).unwrap();
                }
                writeln!(lo, "  return c;").unwrap();
                writeln!(li, "  {t} v{{}};").unwrap();
                for f in &r.fields {
                    let e = self.lift(i, f.ty, &format!("c.{}", field(&f.name)));
                    writeln!(li, "  v.{} = {e};", ident(&f.name)).unwrap();
                }
                writeln!(li, "  return v;").unwrap();
            }
            TypeDefKind::Tuple(tu) => {
                writeln!(lo, "  {ct} c{{}};").unwrap();
                for (n, ty) in tu.types.iter().enumerate() {
                    let e = self.lower(i, *ty, &format!("std::get<{n}>(v)"));
                    writeln!(lo, "  c.f{n} = {e};").unwrap();
                }
                writeln!(lo, "  return c;").unwrap();
                let parts: Vec<String> = tu.types.iter().enumerate().map(|(n, ty)| self.lift(i, *ty, &format!("c.f{n}"))).collect();
                writeln!(li, "  return {t}{{{}}};", parts.join(", ")).unwrap();
            }
            TypeDefKind::Variant(v) => {
                let case_ns = format!("::{}::{}", self.ns(owner_iface(self.wit, id).unwrap()), ident(self.wit.resolve.types[id].name.as_ref().unwrap()));
                writeln!(lo, "  {ct} c{{}};\n  c.tag = static_cast<decltype(c.tag)>(v.index());\n  switch (v.index()) {{").unwrap();
                writeln!(li, "  switch (c.tag) {{").unwrap();
                for (n, case) in v.cases.iter().enumerate() {
                    let cs = format!("{case_ns}::{}", tname(&case.name));
                    match case.ty {
                        Some(ty) => {
                            let e = self.lower(i, ty, &format!("std::get<{n}>(v).value"));
                            writeln!(lo, "    case {n}: c.val.{} = {e}; break;", field(&case.name)).unwrap();
                            let l = self.lift(i, ty, &format!("c.val.{}", field(&case.name)));
                            writeln!(li, "    case {n}: return {t}{{std::in_place_index<{n}>, {cs}{{{l}}}}};").unwrap();
                        }
                        None => writeln!(li, "    case {n}: return {t}{{std::in_place_index<{n}>, {cs}{{}}}};").unwrap(),
                    }
                }
                writeln!(lo, "    default: break;\n  }}\n  return c;").unwrap();
                writeln!(li, "    default: throw ::wna::trap(WNA_TRAP_INVALID, \"{ct}: bad case\");\n  }}").unwrap();
            }
            TypeDefKind::Enum(_) => {
                let n = match self.wit.resolve.types[id].kind {
                    TypeDefKind::Enum(ref e) => e.cases.len(),
                    _ => 0,
                };
                writeln!(lo, "  return static_cast<{ct}>(v);").unwrap();
                writeln!(li, "  if (c >= {n}) throw ::wna::trap(WNA_TRAP_INVALID, \"{ct}: bad case\");\n  return static_cast<{t}>(c);").unwrap();
            }
            TypeDefKind::Option(e) => {
                let le = self.lower(i, e, "*v");
                writeln!(lo, "  {ct} c{{}};\n  if (v) {{ c.is_some = 1; c.val = {le}; }}\n  return c;").unwrap();
                let l = self.lift(i, e, "c.val");
                writeln!(li, "  if (!c.is_some) return std::nullopt;\n  return {t}{{std::in_place, {l}}};").unwrap();
            }
            TypeDefKind::Result(r) => {
                writeln!(lo, "  {ct} c{{}};\n  c.is_err = v.has_value() ? 0 : 1;").unwrap();
                if let Some(ok) = r.ok {
                    let e = self.lower(i, ok, "v.value()");
                    writeln!(lo, "  if (v.has_value()) c.val.ok = {e};").unwrap();
                }
                if let Some(err) = r.err {
                    let e = self.lower(i, err, "v.error()");
                    writeln!(lo, "  if (!v.has_value()) c.val.err = {e};").unwrap();
                }
                writeln!(lo, "  return c;").unwrap();
                let err = r.err.map(|e| self.lift(i, e, "c.val.err")).unwrap_or_else(|| "::wna::unit{}".into());
                let ok = match r.ok {
                    Some(o) => format!("return {t}{{{}}};", self.lift(i, o, "c.val.ok")),
                    None => format!("return {t}{{}};"),
                };
                writeln!(li, "  if (c.is_err) return ::wna::unexpected({err});\n  {ok}").unwrap();
            }
            TypeDefKind::List(e) => {
                let ect = c_type(self.wit, i, e);
                let le = self.lower(i, e, "v[n]");
                writeln!(lo, "  {ct} c{{}};\n  c.len = v.size();\n  c.ptr = cx.array<{ect}>(v.size());\n  for (size_t n = 0; n < v.size(); n++) c.ptr[n] = {le};\n  return c;").unwrap();
                let l = self.lift(i, e, "c.ptr[n]");
                writeln!(li, "  {t} v;\n  v.reserve(c.len);\n  for (size_t n = 0; n < c.len; n++) v.push_back({l});\n  cx.release(c.ptr);\n  return v;").unwrap();
            }
            k => panic!("no helper for {k:?}"),
        }
        let pty = match &self.wit.resolve.types[id].kind {
            TypeDefKind::List(e) => format!("std::span<const {}>", self.ty(*e)),
            _ => format!("const {t}&"),
        };
        writeln!(self.decls, "inline {ct} lower_{ct}({pty} v, ::wna::cx& cx);\ninline {t} lift_{ct}(const {ct}& c, ::wna::cx& cx);").unwrap();
        writeln!(self.helpers, "inline {ct} lower_{ct}({pty} v, [[maybe_unused]] ::wna::cx& cx) {{\n{lo}}}\ninline {t} lift_{ct}(const {ct}& c, [[maybe_unused]] ::wna::cx& cx) {{\n{li}}}\n").unwrap();
        ct
    }

    fn comparable(&self, ty: Type) -> bool {
        match self.wit.dealias(ty) {
            Type::Id(id) => match &self.wit.resolve.types[id].kind {
                TypeDefKind::Record(r) => r.fields.iter().all(|f| self.comparable(f.ty)),
                TypeDefKind::Variant(v) => v.cases.iter().filter_map(|c| c.ty).all(|t| self.comparable(t)),
                TypeDefKind::Option(t) | TypeDefKind::List(t) => self.comparable(*t),
                TypeDefKind::Result(r) => r.ok.iter().chain(r.err.iter()).all(|t| self.comparable(*t)),
                TypeDefKind::Tuple(t) => t.types.iter().all(|t| self.comparable(*t)),
                TypeDefKind::Handle(_) | TypeDefKind::Resource => false,
                _ => true,
            },
            _ => true,
        }
    }

    fn types(&mut self, iface: InterfaceId) -> String {
        let i = self.wit.resolve.interfaces[iface].clone();
        let mut s = docs(&i.docs, "");
        writeln!(s, "namespace {} {{\n", self.ns(iface)).unwrap();
        if self.dirs[&iface] == Dir::Import && self.imports.contains(&iface) {
            writeln!(s, "/// The bound `{}` table (set by the world's `bind`).\ninline wna_iface iface{{}};\n", self.wit.iface_id(iface)).unwrap();
        }
        for (name, &tid) in &i.types {
            let t = self.wit.resolve.types[tid].clone();
            let n = tname(name);
            s.push_str(&docs(&t.docs, ""));
            let eq = |s: &mut String, n: &str, ok: bool| {
                if ok {
                    writeln!(s, "  bool operator==(const {n}&) const = default;").unwrap();
                }
            };
            match &t.kind {
                TypeDefKind::Type(inner) => writeln!(s, "using {n} = {};", self.ty(*inner).trim_start_matches("const ").trim_end_matches('&')).unwrap(),
                TypeDefKind::Record(r) => {
                    writeln!(s, "struct {n} {{").unwrap();
                    for f in &r.fields {
                        s.push_str(&docs(&f.docs, "  "));
                        writeln!(s, "  {} {}{{}};", self.ty(f.ty), ident(&f.name)).unwrap();
                    }
                    eq(&mut s, &n, self.comparable(Type::Id(tid)));
                    writeln!(s, "}};").unwrap();
                }
                TypeDefKind::Variant(v) => {
                    let cmp = self.comparable(Type::Id(tid));
                    writeln!(s, "namespace {} {{", ident(name)).unwrap();
                    for c in &v.cases {
                        let cn = tname(&c.name);
                        match c.ty {
                            Some(ty) => writeln!(s, "struct {cn} {{\n  {} value;", self.ty(ty)).unwrap(),
                            None => writeln!(s, "struct {cn} {{").unwrap(),
                        }
                        eq(&mut s, &cn, cmp);
                        writeln!(s, "}};").unwrap();
                    }
                    writeln!(s, "}}  // namespace {}", ident(name)).unwrap();
                    let cases: Vec<String> = v.cases.iter().map(|c| format!("{}::{}", ident(name), tname(&c.name))).collect();
                    writeln!(s, "using {n} = std::variant<{}>;", cases.join(", ")).unwrap();
                }
                TypeDefKind::Enum(e) => {
                    let int = ["uint8_t", "uint16_t", "", "uint32_t"][discriminant_size(e.cases.len()) - 1];
                    writeln!(s, "enum class {n} : {int} {{ {} }};", e.cases.iter().map(|c| ident(&c.name)).collect::<Vec<_>>().join(", ")).unwrap();
                }
                TypeDefKind::Flags(f) => {
                    let int = ["uint8_t", "uint16_t", "", "uint32_t"][flags_size(f.flags.len()) - 1];
                    let cases: Vec<String> = f.flags.iter().enumerate().map(|(k, fl)| format!("{} = {int}(1u << {k})", ident(&fl.name))).collect();
                    writeln!(
                        s,
                        "enum class {n} : {int} {{ none = 0, {} }};
constexpr {n} operator|({n} a, {n} b) {{ return {n}({int}(a) | {int}(b)); }}
constexpr {n} operator&({n} a, {n} b) {{ return {n}({int}(a) & {int}(b)); }}
constexpr {n} operator^({n} a, {n} b) {{ return {n}({int}(a) ^ {int}(b)); }}
constexpr {n} operator~({n} a) {{ return {n}(~{int}(a)); }}
constexpr bool any({n} a) {{ return {int}(a) != 0; }}",
                        cases.join(", ")
                    )
                    .unwrap();
                }
                TypeDefKind::Resource => match self.dirs[&iface] {
                    Dir::Import => s.push_str(&self.import_resource_decl(iface, name, tid)),
                    Dir::Export => s.push_str(&self.export_resource_decl(iface, name, tid)),
                },
                k => panic!("unsupported named type {k:?}"),
            }
            s.push('\n');
        }
        if self.exports.contains(&iface) {
            s.push_str(&self.exports_decl(iface));
        }
        writeln!(s, "}}  // namespace {}\n", self.ns(iface)).unwrap();
        s
    }

    fn import_resource_decl(&self, iface: InterfaceId, name: &str, tid: TypeId) -> String {
        let n = tname(name);
        let slots = slots(self.wit, iface);
        let drop = slots.iter().find(|s| matches!(s.kind, SlotKind::Drop(r) if r == tid)).map(|s| s.offset).unwrap_or(0);
        let mut s = format!(
            "/// An owned handle to a resource implemented elsewhere (move-only; drops on destruction).
class {n} {{
  uint32_t h_ = 0;
  bool owned_ = true;

 public:
  {n}(::wna::adopt_t, uint32_t h) : h_(h) {{}}
  /// A non-owning view of a borrowed handle, valid for one call.
  static {n} borrow(uint32_t h) {{ {n} r(::wna::adopt, h); r.owned_ = false; return r; }}
  {n}({n}&& o) noexcept : h_(std::exchange(o.h_, 0)), owned_(o.owned_) {{}}
  {n}& operator=({n}&& o) noexcept {{ if (this != &o) {{ close(); h_ = std::exchange(o.h_, 0); owned_ = o.owned_; }} return *this; }}
  {n}(const {n}&) = delete;
  ~{n}() {{ close(); }}
  uint32_t handle() const {{ return h_; }}
  /// Gives up ownership (passing the resource on as `own`).
  uint32_t release() {{ return std::exchange(h_, 0); }}
  void close() {{
    if (owned_ && h_) {{ uint32_t h = std::exchange(h_, 0); wna_call(iface, {drop}, &h, nullptr, wna_libc_alloc()); }}
  }}
"
        );
        for slot in &slots {
            let Some(f) = slot.func() else { continue };
            if resource_of_func(f) != Some(tid) {
                continue;
            }
            let params = self.import_params(f);
            match f.kind {
                FunctionKind::Constructor(_) => writeln!(s, "  explicit {n}({});", params.join(", ")).unwrap(),
                FunctionKind::Method(_) => writeln!(s, "  {} {}({}) const;", self.ret(f), ident(f.item_name()), params.join(", ")).unwrap(),
                _ => writeln!(s, "  static {} {}({});", self.ret(f), ident(f.item_name()), params.join(", ")).unwrap(),
            }
        }
        s.push_str("};\n");
        s
    }

    fn export_resource_decl(&self, iface: InterfaceId, name: &str, tid: TypeId) -> String {
        let n = tname(name);
        let mut s = format!("/// Implement to export the `{name}` resource.\nstruct {n}Resource {{\n  virtual ~{n}Resource() = default;\n");
        for slot in slots(self.wit, iface) {
            let Some(f) = slot.func() else { continue };
            if matches!(f.kind, FunctionKind::Method(r) if r == tid) {
                writeln!(s, "  virtual {} {}({}) = 0;", self.ret(f), ident(f.item_name()), self.export_params(f).join(", ")).unwrap();
            }
        }
        s.push_str("};\n");
        s
    }

    fn exports_decl(&self, iface: InterfaceId) -> String {
        let mut s = format!("/// Implement to export `{}`.\nstruct Exports {{\n  virtual ~Exports() = default;\n", self.wit.iface_id(iface));
        for slot in slots(self.wit, iface) {
            let Some(f) = slot.func() else { continue };
            if matches!(f.kind, FunctionKind::Method(_)) {
                continue;
            }
            s.push_str(&docs(&f.docs, "  "));
            writeln!(s, "  virtual {} {}({}) = 0;", self.ret(f), self.export_fn_name(f), self.export_params(f).join(", ")).unwrap();
        }
        s.push_str("};\n\n/// An instance of the interface served by `impl` (lives for the process).\nwna_iface table(std::shared_ptr<Exports> impl);\n\n");
        let n_res = self.wit.resolve.interfaces[iface].types.values().filter(|t| matches!(self.wit.resolve.types[**t].kind, TypeDefKind::Resource)).count();
        let res: Vec<String> = self.wit.resolve.interfaces[iface]
            .types
            .iter()
            .filter(|(_, t)| matches!(self.wit.resolve.types[**t].kind, TypeDefKind::Resource))
            .enumerate()
            .map(|(k, (n, _))| format!("  ::wna::handles<{}Resource> res{k};\n", tname(n)))
            .collect();
        let _ = n_res;
        writeln!(s, "struct Box {{\n  explicit Box(std::shared_ptr<Exports> i) : impl(std::move(i)) {{}}\n  std::shared_ptr<Exports> impl;\n{}}};\ninline Box* box_of(::wna::cx& cx) {{ return static_cast<Box*>(cx.exports); }}\n", res.concat()).unwrap();
        s
    }

    fn export_fn_name(&self, f: &Function) -> String {
        match f.kind {
            FunctionKind::Constructor(r) => format!("{}_new", ident(self.wit.resolve.types[r].name.as_ref().unwrap())),
            FunctionKind::Static(r) => format!("{}_{}", ident(self.wit.resolve.types[r].name.as_ref().unwrap()), ident(f.item_name())),
            _ => ident(&f.name),
        }
    }

    fn ret(&self, f: &Function) -> String {
        match (f.kind.clone(), f.result) {
            (FunctionKind::Constructor(r), _) => match self.res_dir(r) {
                Dir::Import => self.res_path(r),
                Dir::Export => format!("std::shared_ptr<{}Resource>", self.res_path(r)),
            },
            (_, Some(r)) => self.ty(r),
            (_, None) => "void".into(),
        }
    }

    fn import_params(&self, f: &Function) -> Vec<String> {
        let skip = matches!(f.kind, FunctionKind::Method(_)) as usize;
        f.params.iter().skip(skip).map(|p| format!("{} {}", self.param(p.ty), ident(&p.name))).collect()
    }

    fn export_params(&self, f: &Function) -> Vec<String> {
        let skip = matches!(f.kind, FunctionKind::Method(_)) as usize;
        f.params.iter().skip(skip).map(|p| format!("{} {}", self.ty(p.ty), ident(&p.name))).collect()
    }

    // -----------------------------------------------------------------------

    fn functions(&mut self, iface: InterfaceId) -> String {
        let callable = self.imports.contains(&iface) || self.exports.contains(&iface);
        if !callable {
            return String::new();
        }
        let ns = self.ns(iface);
        let mut s = format!("namespace {ns} {{\n\n");
        let slots = slots(self.wit, iface);
        match self.dirs[&iface] {
            Dir::Import => {
                for slot in &slots {
                    if let Some(f) = slot.func() {
                        s.push_str(&self.import_fn(iface, slot, f));
                    }
                }
            }
            Dir::Export => s.push_str(&self.export_fns(iface, &slots)),
        }
        writeln!(s, "}}  // namespace {ns}\n").unwrap();
        s
    }

    fn import_fn(&mut self, iface: InterfaceId, slot: &Slot, f: &Function) -> String {
        let prefix = self.wit.prefix(iface);
        let params = self.import_params(f);
        let res = resource_of_func(f).map(|r| tname(self.wit.resolve.types[r].name.as_ref().unwrap()));
        let head = match (&f.kind, &res) {
            (FunctionKind::Constructor(_), Some(r)) => format!("inline {r}::{r}({})", params.join(", ")),
            (FunctionKind::Method(_), Some(r)) => format!("inline {} {r}::{}({}) const", self.ret(f), ident(f.item_name()), params.join(", ")),
            (FunctionKind::Static(_), Some(r)) => format!("inline {} {r}::{}({})", self.ret(f), ident(f.item_name()), params.join(", ")),
            _ => format!("{}inline {} {}({})", docs(&f.docs, ""), self.ret(f), ident(&f.name), params.join(", ")),
        };
        let mut b = String::from("  ::wna::cx cx;\n");
        if !f.params.is_empty() {
            writeln!(b, "  {prefix}_{}_args wna_args{{}};", slot.name).unwrap();
        }
        for (n, p) in f.params.iter().enumerate() {
            if n == 0 && matches!(f.kind, FunctionKind::Method(_)) {
                writeln!(b, "  wna_args.{} = h_;", field(&p.name)).unwrap();
                continue;
            }
            let e = self.lower(iface, p.ty, &ident(&p.name));
            writeln!(b, "  wna_args.{} = {e};", field(&p.name)).unwrap();
        }
        let args = if f.params.is_empty() { "nullptr" } else { "&wna_args" };
        let what = format!("{}.{}", self.wit.iface_name(iface).unwrap(), f.name);
        match f.result {
            None => writeln!(b, "  ::wna::invoke(iface, {}, {args}, nullptr, \"{what}\");", slot.offset).unwrap(),
            Some(r) => {
                writeln!(b, "  {prefix}_{}_ret wna_ret{{}};\n  ::wna::invoke(iface, {}, {args}, &wna_ret, \"{what}\");", slot.name, slot.offset).unwrap();
                if matches!(f.kind, FunctionKind::Constructor(_)) {
                    writeln!(b, "  h_ = wna_ret;").unwrap();
                } else {
                    let l = self.lift(iface, r, "wna_ret");
                    writeln!(b, "  return {l};").unwrap();
                }
            }
        }
        format!("{head} {{\n{b}}}\n\n")
    }

    fn export_fns(&mut self, iface: InterfaceId, slots: &[Slot]) -> String {
        let prefix = self.wit.prefix(iface);
        let mut s = String::from("namespace slots {\n");
        let mut names = Vec::new();
        for slot in slots {
            let fname = format!("slot_{}", slot.name);
            names.push(format!("&slots::{fname}"));
            let (args_t, ret_t) = match slot.func() {
                Some(f) => (
                    if f.params.is_empty() { "const void*".to_string() } else { format!("const {prefix}_{}_args*", slot.name) },
                    if f.result.is_some() { format!("{prefix}_{}_ret*", slot.name) } else { "void*".to_string() },
                ),
                None => ("const uint32_t*".to_string(), "void*".to_string()),
            };
            writeln!(
                s,
                "inline int32_t {fname}(void* inst, const void* args_, void* ret_, const wna_alloc* alloc) noexcept {{\n  [[maybe_unused]] auto args = static_cast<{args_t}>(args_);\n  [[maybe_unused]] auto ret = static_cast<{ret_t}>(ret_);\n  return ::wna::guard(inst, alloc, [&]([[maybe_unused]] ::wna::cx& cx) {{\n    [[maybe_unused]] auto* box = static_cast<Box*>(inst);"
            )
            .unwrap();
            match slot.kind {
                SlotKind::Drop(r) => writeln!(s, "    box->res{}.remove(*args);", self.res_index(r)).unwrap(),
                SlotKind::Func(f) => s.push_str(&self.export_body(iface, f)),
            }
            writeln!(s, "  }});\n}}").unwrap();
        }
        writeln!(s, "}}  // namespace slots\n").unwrap();
        writeln!(
            s,
            "inline const {prefix} table_data = {{\n  {{{}, 0, &::wna::detail::last_trap}},\n  {}\n}};\n\ninline wna_iface table(std::shared_ptr<Exports> impl) {{\n  return wna_iface{{&table_data, new Box(std::move(impl))}};\n}}\n",
            table_size(slots),
            names.join(",\n  ")
        )
        .unwrap();
        s
    }

    fn export_body(&mut self, iface: InterfaceId, f: &Function) -> String {
        let mut b = String::new();
        let mut call_args = Vec::new();
        let is_method = matches!(f.kind, FunctionKind::Method(_));
        for (n, p) in f.params.iter().enumerate() {
            if n == 0 && is_method {
                let r = resource_of_func(f).unwrap();
                writeln!(b, "    auto self = box->res{}.get(args->{});", self.res_index(r), field(&p.name)).unwrap();
                continue;
            }
            let l = self.lift(iface, p.ty, &format!("args->{}", field(&p.name)));
            let is_ref = matches!(self.wit.dealias(p.ty), Type::Id(id) if matches!(self.wit.resolve.types[id].kind, TypeDefKind::Handle(Handle::Borrow(_))));
            if is_ref {
                writeln!(b, "    auto&& p{n} = {l};").unwrap();
                call_args.push(format!("p{n}"));
            } else {
                writeln!(b, "    auto p{n} = {l};").unwrap();
                call_args.push(format!("std::move(p{n})"));
            }
        }
        let call = if is_method {
            format!("self->{}({})", ident(f.item_name()), call_args.join(", "))
        } else {
            format!("box->impl->{}({})", self.export_fn_name(f), call_args.join(", "))
        };
        match (f.result, &f.kind) {
            (None, _) => writeln!(b, "    {call};").unwrap(),
            (Some(_), FunctionKind::Constructor(r)) => writeln!(b, "    *ret = box->res{}.insert({call});", self.res_index(*r)).unwrap(),
            (Some(r), _) => {
                let e = self.lower(iface, r, "v");
                writeln!(b, "    auto v = {call};\n    *ret = {e};").unwrap();
            }
        }
        b
    }

    fn world(&self, world: WorldId) -> String {
        let w = &self.wit.resolve.worlds[world];
        let binds: String = self.imports.iter().enumerate().map(|(n, i)| format!("  ::{}::iface = imports[{n}];\n", self.ns(*i))).collect();
        format!(
            "namespace {} {{\n/// The world's imports, in `bind` order.\ninline constexpr const char* imports[] = {{{}}};\ninline void bind([[maybe_unused]] std::span<const wna_iface> imports) {{\n{binds}}}\n}}  // namespace {}\n",
            ident(&w.name),
            self.imports.iter().map(|i| format!("\"{}\"", self.wit.iface_id(*i))).chain(std::iter::once("nullptr".into())).collect::<Vec<_>>().join(", "),
            ident(&w.name)
        )
    }
}
