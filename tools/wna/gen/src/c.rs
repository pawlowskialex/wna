//! C headers: `wna.h` plus one header per interface. These headers are the
//! binary contract; every other binding is checked against the same layouts.

use crate::Files;
use std::fmt::Write;
use wna_abi::wit_parser::*;
use wna_abi::*;

pub const WNA_H: &str = include_str!("wna.h");

/// Emits `wna.h` and a header for each interface in `ifaces`, plus the
/// headers of interfaces they use.
pub fn generate(wit: &Wit, ifaces: &[InterfaceId], out: &mut Files) {
    out.insert("wna.h".into(), WNA_H.into());
    let mut todo: Vec<InterfaceId> = ifaces.to_vec();
    while let Some(i) = todo.pop() {
        let name = header_name(wit, i);
        if out.contains_key(&name) {
            continue;
        }
        out.insert(name, interface_header(wit, i));
        todo.extend(used_interfaces(wit, i));
    }
}

pub fn header_name(wit: &Wit, iface: InterfaceId) -> String {
    format!("{}.h", wit.prefix(iface))
}

/// The C name of any type as seen from `iface`.
pub fn c_type(wit: &Wit, iface: InterfaceId, ty: Type) -> String {
    match ty {
        Type::Bool => "bool".into(),
        Type::U8 => "uint8_t".into(),
        Type::U16 => "uint16_t".into(),
        Type::U32 | Type::Char => "uint32_t".into(),
        Type::U64 => "uint64_t".into(),
        Type::S8 => "int8_t".into(),
        Type::S16 => "int16_t".into(),
        Type::S32 => "int32_t".into(),
        Type::S64 => "int64_t".into(),
        Type::F32 => "float".into(),
        Type::F64 => "double".into(),
        Type::String => "wna_string".into(),
        Type::ErrorContext => "uint32_t".into(),
        Type::Id(id) => {
            let t = &wit.resolve.types[id];
            match &t.kind {
                TypeDefKind::Handle(_) | TypeDefKind::Resource => "uint32_t".into(),
                TypeDefKind::Type(inner) if t.name.is_none() => c_type(wit, iface, *inner),
                _ => match (&t.name, owner_iface(wit, id)) {
                    (Some(n), Some(owner)) => format!("{}_{}", wit.prefix(owner), ident(n)),
                    _ => format!("{}_{}", wit.prefix(iface), mangle(wit, ty)),
                },
            }
        }
    }
}

fn interface_header(wit: &Wit, iface: InterfaceId) -> String {
    let prefix = wit.prefix(iface);
    let guard = format!("{}_H", prefix.to_uppercase());
    let mut s = String::new();
    let id = wit.iface_id(iface);
    writeln!(s, "/* Generated by wna-gen from {id}. Do not edit. */").unwrap();
    writeln!(s, "#ifndef {guard}\n#define {guard}\n").unwrap();
    writeln!(s, "#include \"wna.h\"").unwrap();
    for u in used_interfaces(wit, iface) {
        writeln!(s, "#include \"{}\"", header_name(wit, u)).unwrap();
    }
    writeln!(s, "\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n").unwrap();
    writeln!(s, "#define {}_ID \"{id}\"\n", prefix.to_uppercase()).unwrap();

    // Types: named types of this interface and anonymous types it uses, in
    // dependency order. Named types of other interfaces come from their headers.
    let mut emitted_anon = std::collections::HashSet::new();
    for tid in reachable_types(wit, iface) {
        let t = &wit.resolve.types[tid];
        let owned_here = owner_iface(wit, tid) == Some(iface);
        if t.name.is_some() && !owned_here {
            continue;
        }
        if t.name.is_none() {
            // Anonymous types are structural; one definition per name.
            let n = c_type(wit, iface, Type::Id(tid));
            if !emitted_anon.insert(n) {
                continue;
            }
        }
        type_def(wit, iface, tid, &mut s);
    }

    // Argument structs and result typedefs.
    let slots = slots(wit, iface);
    for slot in &slots {
        let Some(f) = slot.func() else { continue };
        if !f.params.is_empty() {
            writeln!(s, "typedef struct {prefix}_{}_args {{", slot.name).unwrap();
            for p in &f.params {
                writeln!(s, "  {} {};", c_type(wit, iface, p.ty), field(&p.name)).unwrap();
            }
            writeln!(s, "}} {prefix}_{}_args;", slot.name).unwrap();
            let l = wit.args_layout(f).layout;
            static_assert(&mut s, &format!("{prefix}_{}_args", slot.name), l);
        }
        if let Some(r) = f.result {
            writeln!(s, "typedef {} {prefix}_{}_ret;", c_type(wit, iface, r), slot.name).unwrap();
        }
    }

    // The table.
    writeln!(s, "\n/* Function table for {id}. Slots are append-only within a major version. */").unwrap();
    writeln!(s, "typedef struct {prefix} {{\n  wna_table_header hdr;").unwrap();
    let mut last_since = None;
    for slot in &slots {
        if slot.since != last_since {
            if let Some(v) = &slot.since {
                writeln!(s, "  /* since {v} */").unwrap();
            }
            last_since = slot.since.clone();
        }
        let (args, ret) = match slot.func() {
            Some(f) => (
                if f.params.is_empty() { "const void *".to_string() } else { format!("const {prefix}_{}_args *", slot.name) },
                if f.result.is_some() { format!("{prefix}_{}_ret *", slot.name) } else { "void *".to_string() },
            ),
            None => ("const uint32_t *".to_string(), "void *".to_string()),
        };
        // Every slot has the one `wna_fn` type (calling through any other
        // pointer type would be undefined behavior); the comment gives the
        // types `args`/`ret` point to.
        writeln!(s, "  wna_fn {}; /* ({args}args, {ret}ret) */", field(&slot.name)).unwrap();
    }
    writeln!(s, "}} {prefix};").unwrap();
    writeln!(s, "_Static_assert(sizeof({prefix}) == {}, \"table size\");", table_size(&slots)).unwrap();
    for slot in &slots {
        writeln!(s, "_Static_assert(offsetof({prefix}, {}) == {}, \"slot offset\");", field(&slot.name), slot.offset).unwrap();
    }
    writeln!(s, "\n#ifdef __cplusplus\n}}\n#endif\n#endif /* {guard} */").unwrap();
    s
}

fn static_assert(s: &mut String, name: &str, l: Layout) {
    writeln!(s, "_Static_assert(sizeof({name}) == {} && _Alignof({name}) == {}, \"layout of {name}\");\n", l.size, l.align).unwrap();
}

fn type_def(wit: &Wit, iface: InterfaceId, tid: TypeId, s: &mut String) {
    let t = &wit.resolve.types[tid];
    let name = c_type(wit, iface, Type::Id(tid));
    let upper = name.to_uppercase();
    let layout = wit.layout(Type::Id(tid));
    match &t.kind {
        TypeDefKind::Resource => {
            writeln!(s, "/* resource {}: crosses as a uint32_t handle */", t.name.as_deref().unwrap()).unwrap();
            return;
        }
        TypeDefKind::Handle(_) => return,
        TypeDefKind::Type(inner) => {
            if t.name.is_some() {
                writeln!(s, "typedef {} {name};", c_type(wit, iface, *inner)).unwrap();
            }
            return;
        }
        TypeDefKind::Record(r) => {
            writeln!(s, "typedef struct {name} {{").unwrap();
            for f in &r.fields {
                writeln!(s, "  {} {};", c_type(wit, iface, f.ty), field(&f.name)).unwrap();
            }
            writeln!(s, "}} {name};").unwrap();
        }
        TypeDefKind::Tuple(tu) => {
            writeln!(s, "typedef struct {name} {{").unwrap();
            for (n, ty) in tu.types.iter().enumerate() {
                writeln!(s, "  {} f{n};", c_type(wit, iface, *ty)).unwrap();
            }
            writeln!(s, "}} {name};").unwrap();
        }
        TypeDefKind::List(e) => {
            writeln!(s, "typedef struct {name} {{ {} *ptr; size_t len; }} {name};", c_type(wit, iface, *e)).unwrap();
        }
        TypeDefKind::Flags(f) => {
            let int = c_type(wit, iface, [Type::U8, Type::U16, Type::U32][flags_size(f.flags.len()).trailing_zeros() as usize]);
            writeln!(s, "typedef {int} {name};").unwrap();
            for (n, flag) in f.flags.iter().enumerate() {
                writeln!(s, "#define {upper}_{} (({name})1u << {n})", ident(&flag.name).to_uppercase()).unwrap();
            }
        }
        TypeDefKind::Enum(e) => {
            let int = disc_type(e.cases.len());
            writeln!(s, "typedef {int} {name};").unwrap();
            for (n, c) in e.cases.iter().enumerate() {
                writeln!(s, "#define {upper}_{} {n}", ident(&c.name).to_uppercase()).unwrap();
            }
        }
        TypeDefKind::Variant(v) => {
            sum(wit, iface, s, &name, disc_type(v.cases.len()), "tag", v.cases.iter().map(|c| (field(&c.name), c.ty)));
            for (n, c) in v.cases.iter().enumerate() {
                writeln!(s, "#define {upper}_{} {n}", ident(&c.name).to_uppercase()).unwrap();
            }
        }
        TypeDefKind::Option(ty) => {
            writeln!(s, "typedef struct {name} {{\n  uint8_t is_some;\n  {} val;\n}} {name};", c_type(wit, iface, *ty)).unwrap();
        }
        TypeDefKind::Result(r) => {
            sum(wit, iface, s, &name, "uint8_t", "is_err", [("ok".to_string(), r.ok), ("err".to_string(), r.err)].into_iter());
        }
        k => panic!("unsupported type {k:?}"),
    }
    static_assert(s, &name, layout);
}

/// `struct { TAG tag; union { ... } val; }`; the union is omitted when no case has a payload.
fn sum(wit: &Wit, iface: InterfaceId, s: &mut String, name: &str, disc: &str, tag: &str, cases: impl Iterator<Item = (String, Option<Type>)>) {
    let payloads: Vec<_> = cases.filter_map(|(n, t)| t.map(|t| (n, t))).collect();
    writeln!(s, "typedef struct {name} {{\n  {disc} {tag};").unwrap();
    if !payloads.is_empty() {
        writeln!(s, "  union {{").unwrap();
        for (n, t) in &payloads {
            writeln!(s, "    {} {n};", c_type(wit, iface, *t)).unwrap();
        }
        writeln!(s, "  }} val;").unwrap();
    }
    writeln!(s, "}} {name};").unwrap();
}

fn disc_type(n: usize) -> &'static str {
    match discriminant_size(n) {
        1 => "uint8_t",
        2 => "uint16_t",
        _ => "uint32_t",
    }
}

const C_KEYWORDS: &[&str] = &[
    "auto", "break", "case", "char", "const", "continue", "default", "do", "double", "else", "enum", "extern", "float",
    "for", "goto", "if", "inline", "int", "long", "register", "restrict", "return", "short", "signed", "sizeof", "static",
    "struct", "switch", "typedef", "union", "unsigned", "void", "volatile", "while", "bool", "true", "false", "class",
    "delete", "new", "private", "public", "template", "this", "throw", "try", "catch", "operator", "self",
];

/// A field or parameter name, escaped when it collides with a C/C++ keyword.
pub fn field(name: &str) -> String {
    let n = ident(name);
    if C_KEYWORDS.contains(&n.as_str()) { format!("{n}_") } else { n }
}
